// Tailwind v4 @theme export
// ---------------------------------------------------------------------------

interface Pair {
    name: string;
    value: string;
}

/** Parse `--name: value;` declarations out of the primitives block, in order. */
const parsePrimitives = (css: string): Pair[] => {
    const pairs: Pair[] = [];
    const re = /--([\w-]+)\s*:\s*([^;]+);/g;
    let match = re.exec(css);
    while (match !== null) {
        pairs.push({ name: match[1].trim(), value: match[2].trim() });
        match = re.exec(css);
    }
    return pairs;
};

/**
 * Resolve `var(--x, fallback)` references against the primitive map so the
 * Tailwind theme is self-contained (no dependency on tokens.css).
 */
const makeResolver = (map: Map<string, string>) => {
    const resolve = (value: string, depth = 0): string => {
        if (depth > 5) {
            return value;
        }
        const varMatch = value.match(
            /^var\(\s*--([\w-]+)\s*(?:,\s*([^)]+))?\)$/
        );
        if (!varMatch) {
            return value;
        }
        const [, ref, fallback] = varMatch;
        if (map.has(ref)) {
            return resolve(map.get(ref) as string, depth + 1);
        }
        return (fallback ?? value).trim();
    };
    return resolve;
};

/**
 * Map a grauity primitive name to a Tailwind v4 `@theme` namespace, or null to
 * skip. We KEEP the `px`/`percent` suffix on spacing/radius/text so they don't
 * collide with Tailwind's numeric scales and stay 1:1 with Figma token names.
 */
const toTailwindName = (name: string): string | null => {
    if (
        /^(neutral|brand|error|success|warning|yellow|purple|alpha)-/.test(name)
    ) {
        return `--color-${name}`;
    }
    if (name.startsWith('spacing-')) {
        return `--${name}`; // --spacing-16px -> p-16px
    }
    if (name.startsWith('corner-radius-')) {
        return `--radius-${name.slice('corner-radius-'.length)}`;
    }
    if (name.startsWith('font-size-')) {
        return `--text-${name.slice('font-size-'.length)}`;
    }
    if (name.startsWith('font-weight-')) {
        return `--${name}`; // --font-weight-550 -> font-550
    }
    // Intentionally skipped: font-family (font adoption decided separately),
    // backdrop-blur (blur() values aren't Tailwind --blur length tokens),
    // z-index (no Tailwind theme namespace).
    return null;
};

/**
 * Emit a Tailwind v4 `@theme` block from grauity primitives, with values
 * resolved inline so it is self-contained. Generates utilities such as
 * `bg-brand-500`, `p-16px`, `rounded-8px`, `text-16px`, `font-550`.
 */
export const buildTailwindThemeCss = (): string => {
    const primitives = parsePrimitives(constantGlobalStyle);
    const map = new Map(primitives.map((p) => [p.name, p.value]));
    const resolve = makeResolver(map);

    const lines: string[] = [];
    primitives.forEach(({ name, value }) => {
        const twName = toTailwindName(name);
        if (!twName) {
            return;
        }
        lines.push(`    ${twName}: ${resolve(value)};`);
    });

    return `${AUTOGEN_BANNER}

@theme {
${lines.join('\n')}
}
`;
};
