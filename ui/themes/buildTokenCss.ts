import { constantGlobalStyle } from './constantGlobalStyle';
import { ThemeConfigType } from './types';
import { extractColorVariables } from './utils';

/**
 * Pure, dependency-free helpers that turn grauity's design tokens into CSS.
 *
 * Used in two places so the runtime and the shipped static CSS can never drift:
 *  - `GlobalStyle` (runtime) consumes `buildThemeVariables`.
 *  - `scripts/build-tokens.ts` (build time) consumes `buildTokensCss` +
 *    `buildTailwindThemeCss` to emit `dist/css/tokens.css` and
 *    `dist/css/grauity-theme.css`.
 */

/** camelCase -> kebab-case, e.g. `bgActionBrandHover` -> `bg-action-brand-hover`. */
export const camelToKebab = (key: string): string =>
    key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/**
 * CSS custom-property declarations for a single theme: the structured semantic
 * colours (`--bg-*`/`--text-*`/`--border-*`) plus the flat legacy colour
 * aliases and visibility flags. Mirrors exactly what `GlobalStyle` injects per
 * `.grauity-theme-*` scope.
 */
export const buildThemeVariables = (theme: ThemeConfigType): string => {
    const lines: string[] = [];

    // Structured semantic colours -> --bg-*, --text-*, --border-*
    extractColorVariables(theme.colors).forEach((line) =>
        lines.push(String(line))
    );

    // Flat legacy colour aliases (text / background / border) keyed by camelCase.
    const legacy = (theme.legacyColors ?? {}) as Record<
        string,
        Record<string, string>
    >;
    Object.values(legacy).forEach((group) => {
        Object.entries(group ?? {}).forEach(([key, value]) => {
            if (value) {
                lines.push(`--${camelToKebab(key)}: ${value};`);
            }
        });
    });

    // Visibility flags (e.g. --light-visible / --dark-visible).
    const visibility = (theme.visibility ?? {}) as Record<string, string>;
    Object.entries(visibility).forEach(([key, value]) => {
        if (value) {
            lines.push(`--${camelToKebab(key)}: ${value};`);
        }
    });

    return lines.join('\n');
};

const indentBlock = (block: string, pad = '    '): string =>
    block
        .split('\n')
        .map((line) => (line.trim() ? pad + line.trim() : ''))
        .join('\n')
        .replace(/\n{2,}/g, '\n');

export interface ThemeConfigMap {
    light: ThemeConfigType;
    dark: ThemeConfigType;
}

const AUTOGEN_BANNER = `/*
 * AUTO-GENERATED by scripts/build-tokens.ts — do not edit by hand.
 * Source of truth: ui/themes/constantGlobalStyle.ts + {light,dark}ThemeConstants.ts
 */`;

/**
 * The full static token stylesheet (zero-runtime alternative to <GlobalStyle/>):
 *  - primitives at :root
 *  - light semantic at :root + .grauity-theme-light (sensible default)
 *  - dark semantic at .dark + .grauity-theme-dark (Tailwind and grauity scopes)
 */
export const buildTokensCss = ({ light, dark }: ThemeConfigMap): string => {
    return `${AUTOGEN_BANNER}

:root {
${indentBlock(constantGlobalStyle)}
}

:root,
.grauity-theme-light {
${indentBlock(buildThemeVariables(light))}
}

.dark,
.grauity-theme-dark {
${indentBlock(buildThemeVariables(dark))}
}
`;
};

